// Writes lib/projects.generated.json: what the studio needs to know about every project
// (name, database, colours, logos inlined as data URIs). Runs before `next dev` / `next build`;
// commit the result. CI fails when it is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { extname, join } from 'node:path';
import { ROOT } from '../engine/paths.mjs';
import { listProjects, assetPath } from '../engine/project.mjs';

const MIME = { '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp' };
const dataUri = (rel, p) => { const f = rel && assetPath(rel, p); return f ? `data:${MIME[extname(f)]};base64,${readFileSync(f).toString('base64')}` : null; };

const projects = listProjects({ all: true }).map(p => ({
  id: p.id, name: p.name, tagline: p.tagline || '', enabled: p.enabled !== false, db: p.db, web: p.web || '',
  platforms: p.platforms,
  theme: { accent: p.theme.accent, accentDark: p.theme.accentDark, accentSoft: p.theme.accentSoft, accentFaint: p.theme.accentFaint, cta: p.theme.cta, panel: p.theme.panel },
  logo: { mark: dataUri(p.logos.iconOnDark, p), full: dataUri(p.logos.full, p) },
}));
const out = join(ROOT, 'lib', 'projects.generated.json');
writeFileSync(out, JSON.stringify({ note: 'Generated by scripts/sync-projects.mjs from projects/*/project.json - do not edit.', projects }, null, 2) + '\n');
console.log(`studio projects: ${projects.map(p => `${p.id}${p.enabled ? '' : ' (off)'}`).join(', ')}`);
